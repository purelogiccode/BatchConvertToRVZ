namespace RVZStudio.Models;

/// <summary>
/// Specifies which buttons to display in a message box.
/// </summary>
public enum MessageBoxButton
{
    /// <summary>Show a single OK button.</summary>
    Ok,

    /// <summary>Show OK and Cancel buttons.</summary>
    OkCancel,

    /// <summary>Show Yes and No buttons.</summary>
    YesNo
}
