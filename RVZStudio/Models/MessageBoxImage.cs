namespace RVZStudio.Models;

/// <summary>
/// Specifies the icon to display in a message box.
/// </summary>
public enum MessageBoxImage
{
    /// <summary>No icon is shown.</summary>
    None,

    /// <summary>An informational icon is shown.</summary>
    Information,

    /// <summary>A warning icon is shown.</summary>
    Warning,

    /// <summary>An error icon is shown.</summary>
    Error,

    /// <summary>A question icon is shown.</summary>
    Question
}
